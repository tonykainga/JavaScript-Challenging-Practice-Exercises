// Primitive variables
let name = "Tony";          // primitive (string)
let age = 25;               // primitive (number)
let isStudent = true;       // primitive (boolean)
let x;                      // primitive (undefined)
let y = null;               // primitive (null)

// Non-primitive variables
let numbers = [1, 2, 3];    // non-primitive (array)
let person = {              // non-primitive (object)
    name: "Sarabi",
    score: 90
};
let colors = ["red", "blue", "green"]; // non-primitive (array)

//Printing all variables
console.log(name);     // primitive
console.log(age);      // primitive
console.log(isStudent);// primitive
console.log(x);        // primitive
console.log(y);        // primitive

console.log(numbers);  // non-primitive
console.log(person);   // non-primitive
console.log(colors);   // non-primitive