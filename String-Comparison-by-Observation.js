// number vs string
let num = 30;
let strNum = "30";

console.log(typeof num);     // number
console.log(typeof strNum);  // string

// explanation
// 30 is a number (used for calculations)
// "30" is a string (text, even though it looks like a number)


// boolean vs string
let bool = true;
let strBool = "true";

console.log(typeof bool);     // boolean
console.log(typeof strBool);  // string

// explanation
// true is a boolean (true/false value)
// "true" is a string (just text, not a real boolean)